static void test_audio(void) {
    arc__audio_init(44100);
    int ch = 0, rate = 0, frames = 0; int16_t *pcm = arc__qoa_decode_all(test_qoa, sizeof test_qoa, &ch, &rate, &frames);
    CHECK(pcm && ch == 1 && rate == 44100 && frames == 300);
    double err = 0; for (int i = 0; i < frames; i++) { double want = 12000 * sin(i * 2 * 3.14159265358979 * 440 / 44100); err += (pcm[i] - want) * (pcm[i] - want); }
    CHECK(sqrt(err / frames) < 20);                                    /* the encoder reported rms 10.9 */
    arc_sound s = arc_sound_from_memory(test_qoa, sizeof test_qoa); CHECK(s.id != 0 && feq(arc_sound_length(s), 300.0f / 44100));
    uint8_t wav[44 + 8]; memset(wav, 0, sizeof wav);                  /* 2 stereo frames, 16-bit, 22.05 kHz */
    memcpy(wav, "RIFF", 4); wav[4] = 44; memcpy(wav + 8, "WAVEfmt ", 8); wav[16] = 16; wav[20] = 1; wav[22] = 2;
    wav[24] = 0x22; wav[25] = 0x56; wav[34] = 16; memcpy(wav + 36, "data", 4); wav[40] = 8;
    arc_sound w = arc_sound_from_memory(wav, sizeof wav); CHECK(w.id != 0 && feq(arc_sound_length(w), 2.0f / 22050));
    arc_music m = arc_music_from_memory(test_qoa, sizeof test_qoa); CHECK(m.id != 0 && !arc_music_playing(m));
    arc_set_master_volume(1.0f); arc_music_play(m, false); CHECK(arc_music_playing(m));
    float out[2 * 400]; arc__audio_mix(out, 400);                    /* the mixer streams it: same samples, both ears */
    int same = 0; for (int i = 0; i < 300; i++) same += fabsf(out[i * 2] - pcm[i] / 32768.0f) < 1e-4f && out[i * 2] == out[i * 2 + 1];
    CHECK(same == 300); CHECK(out[2 * 350] == 0 && !arc_music_playing(m));   /* not looping: silence, then ended */
    arc_music_play(m, true); arc__audio_mix(out, 400); CHECK(fabsf(out[2 * 310] - pcm[10] / 32768.0f) < 1e-4f && arc_music_playing(m));
    arc_music_stop(m); arc_set_master_volume(0.8f); free(pcm);
}
