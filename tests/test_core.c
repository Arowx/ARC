static void test_turns(void) {
    /* grid: a wall with one gap */
    arc_grid g; CHECK(arc_grid_init(&g, arc_perm(), 8, 5));
    for (int y = 0; y < 5; y++) if (y != 4) arc_grid_set(&g, 4, y, 1);
    CHECK(arc_grid_get(&g, 4, 0, 9) == 1 && arc_grid_get(&g, -1, 0, 9) == 9);
    CHECK(!arc_grid_los(&g, 0, 0, 7, 0, blocks));
    CHECK(arc_grid_los(&g, 0, 4, 7, 4, blocks));
    int nx = -1, ny = -1;
    CHECK(arc_grid_path_step(&g, 0, 0, 7, 0, passable, &nx, &ny) && ((nx == 1 && ny == 0) || (nx == 0 && ny == 1)));
    CHECK(arc_grid_path_length(&g, 0, 0, 7, 0, passable) == 15);   /* down to the gap and back up */
    arc_grid_set(&g, 4, 4, 1);
    CHECK(arc_grid_path_length(&g, 0, 0, 7, 0, passable) == -1);
    /* scheduler: roguelike clock jumps to the next actor; tactical phases alternate */
    arc_actor pl = { 0, 40, 40, 0, true, true }, en = { 5, 40, 40, 1, true, false };
    arc_actor *acts[2] = { &pl, &en };
    arc_turns s; arc_turns_init(&s, ARC_TURNS_ROGUELIKE, 0);
    CHECK(arc_turns_player_ready(&s, &pl));
    arc_turns_spend(&s, &pl, 10, 1.0f);                       /* player busy until 10 */
    CHECK(!arc_turns_player_ready(&s, &pl));
    CHECK(arc_turns_next_ai(&s, acts, 2) == 1 && s.now == 5); /* clock jumped to the enemy */
    arc_turns_spend(&s, &en, 20, 2.0f);                       /* fast enemy: 10 TU */
    CHECK(en.ready_at == 15);
    CHECK(arc_turns_next_ai(&s, acts, 2) == -1 && s.now == 10 && arc_turns_player_ready(&s, &pl));
    arc_turns_set_mode(&s, ARC_TURNS_TACTICAL, acts, 2);
    CHECK(arc_turns_player_ready(&s, &pl) && pl.ap == 40);
    arc_turns_end_player_phase(&s, acts, 2);
    CHECK(s.active_team == 1 && !arc_turns_player_ready(&s, &pl));
    s.ai_timer = 0; CHECK(arc_turns_next_ai(&s, acts, 2) == 1);
    arc_turns_spend(&s, &en, 40, 1.0f); s.ai_timer = 0;
    CHECK(arc_turns_next_ai(&s, acts, 2) == -1);              /* sweep done -> pause */
    s.ai_timer = 0; arc_turns_next_ai(&s, acts, 2);
    CHECK(s.active_team == 0 && s.round == 2 && pl.ap == 40);
    CHECK(!strcmp(arc_turns_mode_name(ARC_TURNS_TACTICAL), "TACTICAL"));
}
