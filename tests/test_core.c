static bool feq(float a, float b) { return fabsf(a - b) < 1e-4f; }

static void test_math(void) {
    arc_m4 m = arc_m4_mul(arc_m4_translate(arc_v3_make(1, 2, 3)), arc_m4_rotate_y(0.7f));
    arc_m4 i = arc_m4_inverse(m), id = arc_m4_mul(m, i);
    for (int k = 0; k < 16; k++) CHECK(feq(id.m[k], (k % 5 == 0) ? 1.0f : 0.0f));
    arc_m4 a = arc_m4_trs_y(arc_v3_make(1, 2, 3), 0.5f, arc_v3_make(2, 3, 4));
    arc_m4 b = arc_m4_mul(arc_m4_mul(arc_m4_translate(arc_v3_make(1, 2, 3)), arc_m4_rotate_y(0.5f)), arc_m4_scale(arc_v3_make(2, 3, 4)));
    for (int k = 0; k < 16; k++) CHECK(feq(a.m[k], b.m[k]));
    CHECK(feq(arc_wrap_angle(ARC_TAU + 0.5f), 0.5f));
    arc_quat q = arc_quat_axis_angle(arc_v3_make(0, 1, 0), 0.5f); arc_m4 qm = arc_m4_from_quat(q), ry = arc_m4_rotate_y(0.5f);
    for (int k = 0; k < 16; k++) CHECK(feq(qm.m[k], ry.m[k]));
}
static void test_rng(void) {
    arc_rng r1, r2; arc_rng_seed(&r1, 42, 1); arc_rng_seed(&r2, 42, 1);
    for (int k = 0; k < 1000; k++) CHECK(arc_rng_u32(&r1) == arc_rng_u32(&r2));
    arc_rng_seed(&r1, 7, 0); arc_rng r3; arc_rng_seed(&r3, 7, 0);
    CHECK(arc_rng_u32(&r1) == arc_rng_u32(&r3));   /* PCG32 reference-stable sequence */
    int lo = 99, hi = -99; for (int k = 0; k < 10000; k++) { int v = arc_rng_range(&r1, -3, 3); lo = arc_mini(lo, v); hi = arc_maxi(hi, v); }
    CHECK(lo == -3 && hi == 3);
}
static void test_pool(void) {
    arc_pool p; arc_pool_make(&p, arc_perm(), int, 4);
    arc_handle h[4]; for (int k = 0; k < 4; k++) { h[k] = arc_pool_add(&p); CHECK(h[k].v != 0); *(int *)arc_pool_get(&p, h[k]) = k; }
    CHECK(arc_pool_add(&p).v == 0);                /* full */
    arc_pool_remove(&p, h[1]);
    CHECK(arc_pool_get(&p, h[1]) == NULL);         /* stale handle rejected */
    arc_handle n = arc_pool_add(&p); CHECK(n.v != 0 && n.v != h[1].v);
    CHECK(p.count == 4);
}
