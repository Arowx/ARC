#!/usr/bin/env python3
"""Writes src/arc_mp3_tables.h: the numeric tables of the MP3 (MPEG-1/2 Audio Layer III) standard, ISO/IEC 11172-3
and 13818-3: Huffman code tables (Annex B.7), scalefactor band widths, pretab, scalefactor bit lengths and the
synthesis window (Annex B.3). These are data from the standard, not code. The values were taken from FFmpeg's
transcription of them (libavcodec/mpegaudiodec_common.c, mpegaudiodsp_data.c), given as an argument folder:

    python3 tools/mp3_tables_gen.py <folder with those two files>

Huffman tables are written as (code, length, x, y) with codes rebuilt from the lengths in listed order (the
listing is in increasing code order), and checked to form complete prefix codes.
"""
import os, re, sys

src = sys.argv[1]
common = open(os.path.join(src, 'mpegaudiodec_common.c')).read()
dsp = open(os.path.join(src, 'mpegaudiodsp_data.c')).read()


def array(text, name):
    m = re.search(re.escape(name) + r'\s*(\[[^\]]*\])*\s*=\s*\{(.*?)\};', text, re.S)
    body = re.sub(r'/\*.*?\*/', '', m.group(2), flags=re.S)
    return [int(v, 0) for v in re.findall(r'-?(?:0x[0-9A-Fa-f]+|\d+)', body)]


lens, syms = array(common, 'mpa_hufflens'), array(common, 'mpa_huffsymbols')
sizes = [n + 1 for n in array(common, 'mpa_huff_sizes_minus_one')]
huff_data = array(common, 'ff_mpa_huff_data')
quad_codes, quad_bits = array(common, 'mpa_quad_codes'), array(common, 'mpa_quad_bits')
band_long, band_short = array(common, 'ff_band_size_long'), array(common, 'ff_band_size_short')
pretab, slen = array(common, 'ff_mpa_pretab'), array(common, 'ff_slen_table')
lsf_nsf = array(common, 'ff_lsf_nsf_table')
enwin = array(dsp, 'ff_mpa_enwindow')
assert len(lens) == len(syms) == sum(sizes) and len(sizes) == 15 and len(enwin) == 257
assert len(band_long) == 9 * 22 and len(band_short) == 9 * 13 and len(lsf_nsf) == 72

out = ['/* Generated by tools/mp3_tables_gen.py: numeric tables of ISO/IEC 11172-3 and 13818-3 (MP3). Do not edit. */',
       '#pragma once', '']
# Huffman: one flat list; codes left-aligned in 32 bits so a decoder can binary-search the next 32 bits
entries, starts, pos = [], [], 0
for t, n in enumerate(sizes):
    starts.append(len(entries))
    code, total = 0, 0.0
    for i in range(n):
        L, s = lens[pos + i], syms[pos + i]
        entries.append((code, L, s >> 4, s & 15))
        code += 1 << (32 - L); total += 2.0 ** -L
    assert abs(total - 1.0) < 1e-12, f'table {t} is not a complete prefix code'
    codes = [e[0] for e in entries[starts[-1]:]]
    assert codes == sorted(codes)
    pos += n
starts.append(len(entries))
out.append('/* Huffman pairs: left-aligned code, length, x, y. Tables 0..14 = the standard\'s 1,2,3,5..13,15,16,24 */')
out.append(f'static const struct {{ uint32_t code; uint8_t len, x, y; }} mp3_huff[{len(entries)}] = {{')
for i in range(0, len(entries), 4):
    out.append('    ' + ' '.join(f'{{ 0x{c:08x}u, {L}, {x}, {y} }},' for c, L, x, y in entries[i:i + 4]))
out.append('};')
out.append(f'static const uint16_t mp3_huff_start[16] = {{ {", ".join(map(str, starts))} }};')
out.append('/* for each table_select 0..31: which of the 15 tables (-1 = all zero) and its linbits */')
ts = [(huff_data[2 * i] - 1, huff_data[2 * i + 1]) for i in range(32)]
out.append('static const int8_t mp3_table_of[32] = { ' + ', '.join(str(a) for a, _ in ts) + ' };')
out.append('static const uint8_t mp3_linbits[32] = { ' + ', '.join(str(b) for _, b in ts) + ' };')
# quad tables A (count1table 0) and B: code, length for v,w,x,y = bits 3..0 of the index
out.append('static const uint8_t mp3_quad_code[2][16] = { { ' + ', '.join(map(str, quad_codes[:16])) + ' }, { ' + ', '.join(map(str, quad_codes[16:])) + ' } };')
out.append('static const uint8_t mp3_quad_len[2][16] = { { ' + ', '.join(map(str, quad_bits[:16])) + ' }, { ' + ', '.join(map(str, quad_bits[16:])) + ' } };')
out.append('/* scalefactor band widths, by rate: 44100 48000 32000 22050 24000 16000 11025 12000 8000 */')
out.append('static const uint8_t mp3_band_long[9][22] = {')
for r in range(9): out.append('    { ' + ', '.join(map(str, band_long[r * 22:(r + 1) * 22])) + ' },')
out.append('};')
out.append('static const uint8_t mp3_band_short[9][13] = {')
for r in range(9): out.append('    { ' + ', '.join(map(str, band_short[r * 13:(r + 1) * 13])) + ' },')
out.append('};')
out.append('static const uint8_t mp3_pretab[22] = { ' + ', '.join(map(str, pretab[22:])) + ' };')
out.append('static const uint8_t mp3_slen[2][16] = { { ' + ', '.join(map(str, slen[:16])) + ' }, { ' + ', '.join(map(str, slen[16:])) + ' } };')
out.append('/* MPEG-2 scalefactor counts per slen group: [table][long, short, mixed][4] */')
out.append('static const uint8_t mp3_lsf_nsf[6][3][4] = {')
for t in range(6): out.append('    { ' + ', '.join('{ ' + ', '.join(map(str, lsf_nsf[t * 12 + k * 4:t * 12 + k * 4 + 4])) + ' }' for k in range(3)) + ' },')
out.append('};')
out.append('/* synthesis window D[0..256] times 65536; D[512 - i] follows by symmetry */')
out.append('static const int32_t mp3_window_half[257] = {')
for i in range(0, 257, 12): out.append('    ' + ' '.join(f'{v},' for v in enwin[i:i + 12]))
out.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'arc_mp3_tables.h'), 'w').write('\n'.join(out) + '\n')
print(f'{len(entries)} Huffman codes in 15 tables; written src/arc_mp3_tables.h')
